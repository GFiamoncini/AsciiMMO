var iconCache = map[string]*ebiten.Image{}

// skillIcon devolve o ícone (12×12) da habilidade na cor do elemento.
func skillIcon(key string, elem int) *ebiten.Image {
	ck := key + "\x00" + string(rune('0'+elem))
	if img, ok := iconCache[ck]; ok {
		return img
	}
	art, ok := iconArt[key]
	if a, ok2 := iconAlias[key]; ok2 {
		art, ok = iconArt[a]
	}
	if !ok {
		art = iconArt["star"]
	}
	pal := elemPal[clampi(elem, 0, len(elemPal)-1)]
	px := make([]byte, 12*12*4)
	for y, row := range art {
		for x := 0; x < 12 && x < len(row); x++ {
			var c col
			switch row[x] {
			case 'o':
				c = col{14, 10, 18}
			case '1':
				c = pal[0]
			case '2':
				c = pal[1]
			case '3':
				c = pal[2]
			case '4':
				c = pal[3]
			case 'a':
				c = pal[4]
			case 'b':
				c = col{120, 82, 48}
			case 's':
				c = col{190, 196, 214}
			default:
				continue
			}
			o := (y*12 + x) * 4
			px[o], px[o+1], px[o+2], px[o+3] = cb(c[0]), cb(c[1]), cb(c[2]), 255
		}
	}
	img := ebiten.NewImage(12, 12)
	img.WritePixels(px)
	iconCache[ck] = img
	return img
}

// drawIcon desenha o ícone num quadrado de lado size (em unidades da tela),
// com fundo escuro, moldura na cor do elemento e o desenho em pixels nítidos.
func (g *Game) drawIcon(dst *ebiten.Image, key string, elem int, x, y, size float64, dim bool) {
	pal := elemPal[clampi(elem, 0, len(elemPal)-1)]
	g.rect(dst, x, y, size, size, color.RGBA{12, 10, 18, 255})
	g.rect(dst, x+2, y+2, size-4, (size-4)*0.5, color.RGBA{uint8(pal[0][0] * 0.25), uint8(pal[0][1] * 0.25), uint8(pal[0][2] * 0.25), 255})
	img := skillIcon(key, elem)
	op := &ebiten.DrawImageOptions{}
	pad := size * 0.12
	op.GeoM.Scale((size-2*pad)*g.ui/12, (size-2*pad)*g.ui/12)
	op.GeoM.Translate((x+pad)*g.ui, (y+pad)*g.ui)
	op.Filter = ebiten.FilterNearest
	if dim {
		op.ColorScale.Scale(0.35, 0.35, 0.4, 1)
	}
	dst.DrawImage(img, op)
	g.stroke(dst, x, y, size, size, pal[1].rgba(), 1.5)
}
